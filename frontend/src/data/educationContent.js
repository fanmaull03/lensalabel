export function getReadMinutes(body) {
  const text = body.flatMap((block) => block.type === "list" ? block.items : [block.text]).join(" ");
  const withoutCitations = text.replace(/\[\d+(?:,\s*\d+)*\]/g, "");
  const words = withoutCitations.trim().match(/\S+/g) ?? [];
  return Math.max(1, Math.ceil(words.length / 200));
}
